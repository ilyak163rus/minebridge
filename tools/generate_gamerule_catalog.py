"""Generate typed GameRule constants from the actual pinned server snapshot, offline."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SNAPSHOT = ROOT / "catalogs/paper-26.2-build133-gamerules.json"


def generate() -> dict[Path, str]:
    payload = SNAPSHOT.read_bytes()
    snapshot = json.loads(payload)
    assert snapshot["minecraftVersion"] == "26.2" and snapshot["paperBuild"] == 133
    assert snapshot["source"]["paper"]["sha256"] == "bf1dcf627364f8a631ab15250d240eb5a8e89faaac523b391e1c61367fce9ff1"
    assert snapshot["source"]["paperApi"]["sha256"] == "e8079e853374d75e571a24379573e96f6dfe1581b97bae5465163c77f00f327a"
    rows = snapshot["rules"]
    keys = [row["key"] for row in rows]
    assert keys and keys == sorted(set(keys))
    constants = {}
    for row in rows:
        assert re.fullmatch(r"minecraft:[a-z0-9_]+", row["key"])
        assert re.fullmatch(r"[A-Z][A-Z0-9_]*", row["constant"])
        value_type = {"bool": bool, "int": int}[row["valueType"]]
        assert type(row["defaultValue"]) is value_type
        for constant in [row["constant"], *row["aliases"]]:
            assert re.fullmatch(r"[A-Z][A-Z0-9_]*", constant) and constant not in constants
            constants[constant] = row
    omitted = {row["constant"] for row in snapshot["unsupportedLegacyAliases"]}
    assert not omitted.intersection(constants)
    lines = [
        '"""Typed canonical gamerules and identity-safe aliases for Paper 26.2 build 133.',
        "", "Generated by tools/generate_gamerule_catalog.py; no server connection is required.",
        "Legacy conversion/inversion wrappers are deliberately not misleading aliases.", '"""', "",
        "from typing import Final", "", "from .models.controls import GameRuleKey", "", "__all__ = [",
        *(f'    "{name}",' for name in sorted(constants)), "]", "",
    ]
    for name, row in sorted(constants.items()):
        annotation = f"Final[GameRuleKey[{row['valueType']}]]"
        if name == row["constant"]:
            lines.append(f"{name}: {annotation} = GameRuleKey({row['key']!r}, {row['valueType']}, {row['defaultValue']!r})")
        else:
            # Aliases are emitted after all canonical definitions to avoid declaration order dependencies.
            continue
    lines.append("")
    for name, row in sorted(constants.items()):
        if name != row["constant"]:
            lines.append(f"{name}: Final[GameRuleKey[{row['valueType']}]] = {row['constant']}")
    lines.extend(["", "_BY_KEY: dict[str, GameRuleKey[bool] | GameRuleKey[int]] = {",
                  *(f"    {row['key']!r}: {row['constant']}," for row in rows), "}", ""])
    runtime = {
        "formatVersion": 1, "minecraftVersion": "26.2", "paperBuild": 133,
        "sourceSha256": hashlib.sha256(payload).hexdigest(), "rules": rows,
        "unsupportedLegacyAliases": snapshot["unsupportedLegacyAliases"],
    }
    return {
        ROOT / "python/src/minebridge/gamerule.py": "\n".join(lines),
        ROOT / "python/src/minebridge/_data/gamerules-paper-26.2.json": json.dumps(runtime, indent=2) + "\n",
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, content in generate().items():
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != content:
                raise SystemExit("Generated catalog differs: " + str(path))
        else:
            path.write_text(content, encoding="utf-8")
        print(path.relative_to(ROOT))


if __name__ == "__main__":
    main()
