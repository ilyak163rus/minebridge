"""Generate static typed item/effect/entity catalogs from the pinned Paper snapshot.

Offline and deterministic; --check verifies generated files without writing.
The full entity registry includes PLAYER, whose spawn restriction is documented
in the packaged matrix. A catalog entry is not a lifetime or gameplay promise.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SNAPSHOT = ROOT / "catalogs/paper-26.2-build133-game.json"


def generate() -> dict[Path, str]:
    snapshot = json.loads(SNAPSHOT.read_text(encoding="utf-8"))
    assert snapshot["minecraftVersion"] == "26.2"
    assert snapshot["source"]["paper"]["sha256"] == "bf1dcf627364f8a631ab15250d240eb5a8e89faaac523b391e1c61367fce9ff1"
    outputs = {}
    for collection, module, key_type in (
        ("items", "items", "ItemKey"),
        ("effects", "effects", "EffectKey"),
        ("entities", "entity", "EntityTypeKey"),
    ):
        rows = snapshot[collection]
        keys = [row["key"] for row in rows]
        assert keys == sorted(set(keys)) and keys
        constants = []
        for key in keys:
            namespace, name = key.split(":", 1)
            assert namespace == "minecraft" and re.fullmatch(r"[a-z_0-9]+", name)
            constants.append((name.upper(), key))
        constants.sort()
        lines = [f'"""Offline {module} constants for pinned Paper 26.2 build 133.', "",
                 "Generated by tools/generate_game_catalog.py; do not edit manually.",
                 "Keys represent the actual registry, not guaranteed gameplay or spawnability.",
                 '"""', "", "from typing import Final", "",
                 f"from .models.keys import {key_type}", "", "__all__ = ["]
        lines.extend(f'    "{name}",' for name, _ in constants)
        lines.extend([
            "]", "",
            *(f'{name}: Final[{key_type}] = {key_type}("{key}")' for name, key in constants), "",
        ])
        outputs[ROOT / f"python/src/minebridge/{module}.py"] = "\n".join(lines)
    rows = snapshot["entities"]
    assert all(row["spawnCategory"] in ("generic", "special", "unsupported") for row in rows)
    assert all(row["genericProbe"]["status"] == "created" for row in rows if row["spawnCategory"] == "generic")
    assert [row["key"] for row in rows if row["spawnCategory"] == "unsupported"] == ["minecraft:player"]
    assert all(row["reason"] and row["adapter"] for row in rows if row["spawnCategory"] == "special")
    runtime = {
        "formatVersion": 1,
        "minecraftVersion": snapshot["minecraftVersion"],
        "paperBuild": 133,
        "sourceSha256": hashlib.sha256(SNAPSHOT.read_bytes()).hexdigest(),
        "items": snapshot["items"],
        "effects": snapshot["effects"],
        "entities": [{key: row[key] for key in ("key", "spawnCategory", "requiredParameters", "adapter", "reason")}
                     for row in rows],
    }
    outputs[ROOT / "python/src/minebridge/_data/game-paper-26.2.json"] = json.dumps(runtime, indent=2) + "\n"
    return outputs


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, content in generate().items():
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != content:
                raise SystemExit("Generated catalog differs: " + str(path))
        else:
            path.write_text(content, encoding="utf-8")
        print(path.relative_to(ROOT))


if __name__ == "__main__":
    main()
