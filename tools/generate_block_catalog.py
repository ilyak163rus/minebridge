"""Generate offline typed constants and legacy data from a checked-in snapshot.

No server/network/import of minebridge is needed. `--check` verifies reproducible
outputs without writing. Refresh the snapshot with export_block_catalog.py.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SNAPSHOT = ROOT / "catalogs/paper-26.2-build133-blocks.json"
UPSTREAM = ROOT / "catalogs/mcpi-upstream-constants.json"


def parse_data(value: str) -> tuple[str, dict[str, str]]:
    key, separator, properties = value.partition("[")
    return key, dict(part.split("=", 1) for part in properties[:-1].split(",")) if separator else {}


def generate() -> dict[Path, str]:
    snapshot = json.loads(SNAPSHOT.read_text(encoding="utf-8"))
    upstream = json.loads(UPSTREAM.read_text(encoding="utf-8"))
    assert snapshot["minecraftVersion"] == "26.2"
    assert snapshot["source"]["paper"]["sha256"] == "bf1dcf627364f8a631ab15250d240eb5a8e89faaac523b391e1c61367fce9ff1"
    keys = [row["key"] for row in snapshot["blocks"]]
    assert keys == sorted(set(keys)) and len(keys) > 1000
    constants: dict[str, tuple[str, str]] = {}
    for key in keys:
        namespace, name = key.split(":", 1)
        assert namespace == "minecraft" and re.fullmatch(r"[a-z_0-9]+", name)
        constants[name.upper()] = ("BlockSpec", f'BlockSpec("{key}")')
    conversions = []
    pairs = set()
    for row in snapshot["legacyConversions"]:
        key, states = parse_data(row["blockData"])
        pair = row["id"], row["data"]
        assert pair not in pairs and key in keys
        pairs.add(pair)
        # An unsupported legacy material must never silently turn into air.
        assert key != "minecraft:air" or pair == (0, 0), pair
        conversion = {"id": pair[0], "data": pair[1], "key": key}
        if states:
            conversion["states"] = states
        conversions.append(conversion)
    excluded = []
    legacy_names: dict[str, tuple[int, int]] = {}
    for row in upstream["constants"]:
        name = row["name"]
        if name == "BEDROCK_INVISIBLE" or row.get("id") in (246, 247):
            excluded.append(name)
            continue
        if "alias" in row:
            constants[name] = constants[row["alias"]]
            legacy_names[name] = legacy_names[row["alias"]]
        else:
            pair = row["id"], row["data"]
            assert pair in pairs, pair
            # Retain historical constants' .id/.data while modern-only names use BlockSpec.
            constants[name] = ("LegacyBlock", f"LegacyBlock({pair[0]}, {pair[1]})")
            legacy_names[name] = pair
    pair_keys = {(row["id"], row["data"]): row["key"] for row in conversions}
    collisions = {}
    for key in keys:
        name = key.split(":", 1)[1].upper()
        if name in legacy_names and pair_keys[legacy_names[name]] != key:
            modern_name = "MINECRAFT_" + name
            assert modern_name not in constants
            constants[modern_name] = ("BlockSpec", f'BlockSpec("{key}")')
            collisions[name] = modern_name
    names = sorted(constants)
    lines = ['"""Offline block constants for pinned Paper 26.2 build 133.',
             '', 'Generated by tools/generate_block_catalog.py; do not edit manually.',
             'Historical mcpi names retain LegacyBlock; other names use BlockSpec.',
             'Availability of a constant does not promise placement of multi-block structures.',
             '"""', '', 'from typing import Final', '',
             'from .models.blocks import BlockSpec, LegacyBlock', '', '__all__ = [']
    lines.extend(f'    "{name}",' for name in names)
    lines.extend([']', ''])
    for name in names:
        kind, value = constants[name]
        lines.append(f'{name}: Final[{kind}] = {value}')
    lines.append('')
    legacy = {"formatVersion": 1, "profile": "mcpi-legacy-v0.2-paper26.2", "source": {
        "upstreamConstants": upstream["source"],
        "modernConversion": "Pinned Paper Bukkit.getUnsafe().fromLegacy(Material, byte), exported without world mutation",
        "snapshot": "catalogs/paper-26.2-build133-blocks.json",
        "snapshotSha256": hashlib.sha256(SNAPSHOT.read_bytes()).hexdigest(),
        "note": "Explicitly requested metadata only; not all legacy IDs/data. Full converted states preserve legacy orientation. Java numeric semantics; Pi-only aliases are excluded. 8/9 water and 10/11 lava can share a modern state, so reverse numeric reads may be ambiguous.",
        "excludedConstants": excluded,
        "modernNameCollisions": collisions,
    }, "blocks": sorted(conversions, key=lambda row: (row["id"], row["data"]))}
    package_registry = {"formatVersion": 1, "minecraftVersion": snapshot["minecraftVersion"],
        "paperBuild": 133, "sourceSha256": legacy["source"]["snapshotSha256"],
        "blocks": [{"key": row["key"], "defaultStates": parse_data(row["defaultBlockData"])[1]} for row in snapshot["blocks"]]}
    return {
        ROOT / "python/src/minebridge/block.py": "\n".join(lines),
        ROOT / "python/src/minebridge/_data/legacy-blocks-v0.2.json": json.dumps(legacy, indent=2) + "\n",
        ROOT / "python/src/minebridge/_data/blocks-paper-26.2.json": json.dumps(package_registry, indent=2) + "\n",
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, content in generate().items():
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != content:
                raise SystemExit("Generated catalog differs: " + str(path))
        else:
            path.write_text(content, encoding="utf-8")
        print(path.relative_to(ROOT))


if __name__ == "__main__":
    main()
