def archives(wheel: Path, sdist: Path, jar: Path) -> dict:
    previous.VERSION = VERSION
    previous.REQUIRED |= REQUIRED_V03
    result = previous.archives(wheel, sdist, jar)
    with zipfile.ZipFile(wheel) as archive:
        names = archive.namelist()
        wheel_metadata = archive.read(next(name for name in names if name.endswith(".dist-info/WHEEL"))).decode("utf-8")
        previous.require("84.2.0" in wheel_metadata, "Wheel was not generated by pinned setuptools84.2.0")
        previous.require(all(info.date_time == time.gmtime(EPOCH)[:6] for info in archive.infolist()),
                         "Wheel timestamps differ from the frozen SOURCE_DATE_EPOCH")
        rules = json.loads(archive.read("minebridge/_data/gamerules-paper-26.2.json"))
        previous.require(len(rules["rules"]) == 59, "Wrong canonical gamerule registry coverage")
        result["registryCounts"].update(canonicalGameRules=59, gameruleConstants=82,
                                        damageCauses=33, eventTypes=14, equipmentSlots=5)
    previous.require(struct.unpack("<I", sdist.read_bytes()[4:8])[0] == EPOCH,
                     "sdist gzip timestamp is not normalized")
    with tarfile.open(sdist, "r:gz") as archive:
        members = archive.getmembers()
        previous.require(all(member.mtime == EPOCH and member.uid == member.gid == 0
                             and not member.uname and not member.gname for member in members),
                         "sdist tar metadata is not normalized")
    result["archiveMetadata"] = {"sourceDateEpoch": EPOCH, "wheelTimestampsFrozen": True,
                                 "sdistGzipAndTarMetadataNormalized": True}
    with zipfile.ZipFile(jar) as archive:
        names = set(archive.namelist())
        required = {"dev/minebridge/BridgePlugin.class", "dev/minebridge/events/EventsService.class",
                    "dev/minebridge/events/LavaContactMonitor.class", "dev/minebridge/inventories/InventoryService.class",
                    "dev/minebridge/inventories/PaperInventoryBackend.class", "dev/minebridge/inventories/InventoryJobManager.class"}
        previous.require(required <= names, "Production JAR misses the final event/inventory services")
        previous.require(not any(name.startswith(("dev/minebridge/observer/", "com/fasterxml/jackson/"))
                                 or name.endswith("Test.class") for name in names),
                         "Production JAR includes observer/tests or unrelocated Jackson")
        previous.require(any(name.startswith("dev/minebridge/internal/jackson/core/") for name in names),
                         "Relocated Jackson is missing")
        header = archive.read("dev/minebridge/BridgePlugin.class")[:8]
        magic, minor, major = struct.unpack(">IHH", header)
        previous.require(magic == 0xCAFEBABE and major == 69, "Wrong production Java class level")
        result["jarAudit"] = {"version": VERSION, "javaClassMajor": major,
                              "observerAndTestsExcluded": True, "jacksonRelocated": True}
    return result


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ("wheel", "sdist", "jar"):
        parser.add_argument("--" + name, type=Path, required=True)
    parser.add_argument("--python", type=Path, action="append", required=True)
    parser.add_argument("--output", type=Path, default=ROOT / ".work/v03-i05-package-results.json")
    args = parser.parse_args()
    result = {"passed": False}
    try:
        result.update(archives(args.wheel.resolve(), args.sdist.resolve(), args.jar.resolve()))
        generated = []
        for name in ("generate_block_catalog.py", "generate_game_catalog.py", "generate_gamerule_catalog.py",
                     "generate_damage_cause_catalog.py", "export_damage_cause_catalog.py"):
            completed = subprocess.run([sys.executable, "-I", str(ROOT / "tools" / name), "--check"],
                                       cwd=ROOT, text=True, capture_output=True, timeout=60)
            previous.require(completed.returncode == 0, "Generated catalog differs: " + completed.stdout + completed.stderr)
            generated.append(name)
        result["generatorsChecked"] = generated
        result["installedInterpreters"] = []
        with tempfile.TemporaryDirectory(prefix="minebridge-v03-offline-") as outside:
            for python in args.python:
                completed = subprocess.run([str(python.resolve()), "-I", "-c", INSTALLED_CHECK, VERSION],
                                           cwd=outside, text=True, capture_output=True, timeout=30)
                previous.require(completed.returncode == 0, "Installed import failed: " + completed.stdout + completed.stderr)
                runtime = json.loads(completed.stdout)
                previous.require(not any(Path(entry).resolve() == ROOT / "python/src" for entry in runtime["sysPath"]),
                                 "Repository source leaked into isolated interpreter")
                result["installedInterpreters"].append(runtime)
        result["passed"] = True
        print(json.dumps(result, indent=2))
    finally:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
